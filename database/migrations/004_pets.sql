
CREATE TABLE public.pets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES public.clientes(id) ON DELETE CASCADE,
    nome TEXT NOT NULL,
    especie TEXT NOT NULL,
    peso NUMERIC(6,2),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.pets ENABLE ROW LEVEL SECURITY;

-- ADMIN e FUNCIONARIO podem consultar
CREATE POLICY "Consultar pets"
ON public.pets
FOR SELECT TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.perfis
        WHERE id = auth.uid()
        AND tipo IN ('ADMIN', 'FUNCIONARIO')
    )
);

-- ADMIN e FUNCIONARIO podem cadastrar
CREATE POLICY "Cadastrar pets"
ON public.pets
FOR INSERT TO authenticated
WITH CHECK (
    EXISTS (
        SELECT 1 FROM public.perfis
        WHERE id = auth.uid()
        AND tipo IN ('ADMIN', 'FUNCIONARIO')
    )
);

-- ADMIN e FUNCIONARIO podem editar
CREATE POLICY "Editar pets"
ON public.pets
FOR UPDATE TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.perfis
        WHERE id = auth.uid()
        AND tipo IN ('ADMIN', 'FUNCIONARIO')
    )
)
WITH CHECK (
    EXISTS (
        SELECT 1 FROM public.perfis
        WHERE id = auth.uid()
        AND tipo IN ('ADMIN', 'FUNCIONARIO')
    )
);

-- Somente ADMIN pode excluir
CREATE POLICY "Excluir pets"
ON public.pets
FOR DELETE TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.perfis
        WHERE id = auth.uid()
        AND tipo = 'ADMIN'
    )
);
