
CREATE TABLE public.agendamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES public.clientes(id) ON DELETE RESTRICT,
    servico_id BIGINT NOT NULL REFERENCES public.servicos(id) ON DELETE RESTRICT,
    data_agendamento DATE NOT NULL,
    horario TIME NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT horario_agendamento_unico
    UNIQUE (data_agendamento, horario)
);

ALTER TABLE public.agendamentos ENABLE ROW LEVEL SECURITY;

-- ADMIN e FUNCIONARIO podem consultar
CREATE POLICY "Consultar agendamentos"
ON public.agendamentos
FOR SELECT TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.perfis
        WHERE id = auth.uid()
        AND tipo IN ('ADMIN', 'FUNCIONARIO')
    )
);

-- ADMIN e FUNCIONARIO podem cadastrar
CREATE POLICY "Cadastrar agendamentos"
ON public.agendamentos
FOR INSERT TO authenticated
WITH CHECK (
    EXISTS (
        SELECT 1 FROM public.perfis
        WHERE id = auth.uid()
        AND tipo IN ('ADMIN', 'FUNCIONARIO')
    )
);

-- ADMIN e FUNCIONARIO podem editar
CREATE POLICY "Editar agendamentos"
ON public.agendamentos
FOR UPDATE TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.perfis
        WHERE id = auth.uid()
        AND tipo IN ('ADMIN', 'FUNCIONARIO')
    )
)
WITH CHECK (
    EXISTS (
        SELECT 1 FROM public.perfis
        WHERE id = auth.uid()
        AND tipo IN ('ADMIN', 'FUNCIONARIO')
    )
);

-- Somente ADMIN pode excluir
CREATE POLICY "Excluir agendamentos"
ON public.agendamentos
FOR DELETE TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.perfis
        WHERE id = auth.uid()
        AND tipo = 'ADMIN'
    )
);
