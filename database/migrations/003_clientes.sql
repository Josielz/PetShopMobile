
CREATE TABLE public.clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_completo TEXT NOT NULL,
    documento TEXT NOT NULL UNIQUE,
    email TEXT,
    telefone TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.clientes ENABLE ROW LEVEL SECURITY;

-- ADMIN e FUNCIONARIO podem consultar
CREATE POLICY "Consultar clientes"
ON public.clientes
FOR SELECT TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.perfis
        WHERE id = auth.uid()
        AND tipo IN ('ADMIN', 'FUNCIONARIO')
    )
);

-- ADMIN e FUNCIONARIO podem cadastrar
CREATE POLICY "Cadastrar clientes"
ON public.clientes
FOR INSERT TO authenticated
WITH CHECK (
    EXISTS (
        SELECT 1 FROM public.perfis
        WHERE id = auth.uid()
        AND tipo IN ('ADMIN', 'FUNCIONARIO')
    )
);

-- ADMIN e FUNCIONARIO podem editar
CREATE POLICY "Editar clientes"
ON public.clientes
FOR UPDATE TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.perfis
        WHERE id = auth.uid()
        AND tipo IN ('ADMIN', 'FUNCIONARIO')
    )
)
WITH CHECK (
    EXISTS (
        SELECT 1 FROM public.perfis
        WHERE id = auth.uid()
        AND tipo IN ('ADMIN', 'FUNCIONARIO')
    )
);

-- Somente ADMIN pode excluir
CREATE POLICY "Excluir clientes"
ON public.clientes
FOR DELETE TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM public.perfis
        WHERE id = auth.uid()
        AND tipo = 'ADMIN'
    )
);
